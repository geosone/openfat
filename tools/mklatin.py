#!/usr/bin/env python3
"""Generates src/latin.c: the base letter A-Z of the accented Latin
letters U+00C0-U+024F, from the canonical decompositions of
UnicodeData.txt (mars-unicode-tables, UCD/UnicodeData.txt). DOS upper
case falls back to it when a code page lacks the accented capital.
python3 tools/mklatin.py UnicodeData.txt > src/latin.c"""
import sys

FIRST, LAST = 0xC0, 0x24F
dec = {}
for line in open(sys.argv[1], encoding='ascii'):
    f = line.split(';')
    if f[5] and not f[5].startswith('<'):
        dec[int(f[0], 16)] = int(f[5].split()[0], 16)


def base(u):
    while u in dec:
        u = dec[u]
    return u


out = []
for u in range(FIRST, LAST + 1):
    b = base(u)
    out.append(ord(chr(b).upper()) if chr(b).isascii() and chr(b).isalpha() else 0)
print('/* Generated by tools/mklatin.py from UnicodeData.txt: the base letter')
print('   (A-Z) of the Latin letters U+%04X-U+%04X, 0 for none. */' % (FIRST, LAST))
print('#include "openfat/codepage.h"')
print('static const char base[%d] =' % (len(out) + 1))
for i in range(0, len(out), 32):
    print('    "' + ''.join(chr(c) if c else '\\0' for c in out[i:i + 32]) + '"')
print(';')
print('ofat_u8 ofat_latin_base(ofat_u16 u)')
print('{')
print('    return u >= 0x%X && u <= 0x%X ? (ofat_u8)base[u - 0x%X] : 0;' % (FIRST, LAST, FIRST))
print('}')
